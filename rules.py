assert set(_ORD) >= {c for c, _ in CATS} | {c for c, _ in CATS_DESC}, '並び順にないカテゴリがある'
CAT_ORDER = [c for c in _ORD if c != '外国']   # 表示するカテゴリ。「外国」は判定の途中だけの名前で、tag.py が「海外」にまとめる（依頼者の判断、2026-11-20）   # 同じ名前は1つに
def cats(t, desc=''):
    t, desc = nf(t), nf(desc)
    out = [c for c, rx in CATS if rx.search(t)] + (['海外'] if FOREIGN_END.search(t) else []) + [c for c, rx in CATS_DESC if rx.search(desc)]
    if '党大会' in t: out.append('政党')   # 見出しに「党大会」（依頼者の判断、2026-11-20）
    if OPPOSITION_HEAD.match(t): out.append('政党')   # 見出しが「野党、」「（野党の略称）、」で始まる（依頼者の判断、2026-11-21）
    if not out and GAIKOKU.search(desc): out = ['外国']   # ほかのカテゴリに入らず、抜粋に【〜時事】がある記事（依頼者の判断、2026-11-20）。表示は「海外」
    return sorted(set(out), key=_ORD.index) or [NONE]   # 見出しと抜粋の両方で同じカテゴリに当たっても1つ

# ---- 落とす規則。見出し（t）・説明文（desc）・サイト名（site）で決める。当たれば載せない
DROP_TITLE = re.compile(r'【速報】')   # 【速報】の記事は載せない（依頼者の判断、2026-11-20）
DROP_DESC = None
DROP_SITES = set()   # 例：{'〇〇新聞'}
# 見出しにあれば、DROP に当たっても残す語
KEEP_TITLE = None

def keep(t, desc='', site=''):
    """記事を載せるなら True"""
    t, desc = nf(t), nf(desc)
    if KEEP_TITLE and KEEP_TITLE.search(t): return True
    if site in DROP_SITES: return False
    if DROP_TITLE and DROP_TITLE.search(t): return False
    if DROP_DESC and DROP_DESC.search(desc): return False
    return True

